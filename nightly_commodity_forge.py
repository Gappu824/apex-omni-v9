"""
APEX OMNI v9.7.1 — COMMODITY FORGE (trains the commodity meta-labeler)
=====================================================================
The commodity analog of the equity forge's meta-training path. It closes the
last gap: the commodity brain runs heuristic-only until THIS produces a
promoted model — exactly how the equity brain crossed the same boundary.

Zero-divergence design (every load-bearing piece is REUSED, not re-implemented)
------------------------------------------------------------------------------
  • Vault reading:  simulation.replay_real_day.load_day — the SAME loader the
    equity forge uses. Its query carries no token filter, so bidA/askA/by_sec
    already cover every harvested commodity token (futures + option legs).
  • Instruments:    core.instruments.AsOfMapper — the harvester snapshots
    commodity chains daily (write_snapshot writes self._rows, which includes
    the MCX rows), so historical replay resolves commodity chains natively.
  • Side decision:  core.commodity_brain.CommodityHeuristicPolicy over nodes
    built by the SAME StateBuilder.leg_features — the live brain's exact
    signal path, so labels are generated by the policy that will be gated.
  • Barriers/costs: nightly_forge_v9._shaped_barriers, _hold_seconds,
    round_trip_costs — identical first-touch triple-barrier grading.
  • Trainer:        core.meta_gbm.fit_gbm — the SAME purged-day-fold LightGBM
    + weighted-isotonic pipeline (universe-agnostic by interface). Fail-open:
    if lightgbm is absent or CV is too thin it returns None and the commodity
    brain simply STAYS heuristic-only. A missing package can never fake a model.
  • Labels carry AFML uniqueness weights (mean 1/concurrency over the span),
    per commodity — same as equity.

Sample x-vector (MUST match serving; commodity_brain builds the identical x):
  [spot_node(19), atm_ce_node(19), atm_pe_node(19), t/N, kaufman_er,
   capped_mom30, +1 if CE else -1]                                  → 61 dims

Data-gated by design: with an empty/thin commodity vault it logs
"keep harvesting" and writes nothing. COMMODITY_META_MIN_TRAIN gates training;
the artifact goes to MODEL_DIR/commodity_meta.json, which
core.commodity_brain.load_commodity_meta already reads.

  python nightly_commodity_forge.py [--days N]
"""
